function analysisMarkdown(a: Asset): string {
  const x: ImageAnalysis = a.analysis;
  const pct = (v: number, d = 0) => `${(v * 100).toFixed(d)}%`;
  return [
    `# Analysis — ${mdEscape(a.name)}`,
    "",
    `${x.width}×${x.height} px, ${x.aspect.label}, ${x.kind.toUpperCase()}`,
    "",
    "## What the pixels show",
    "",
    ...observationsToMarkdown(observeImage(x)),
    "## Palette (measured)",
    "",
    "| Colour | Share |",
    "| --- | --- |",
    ...x.palette.swatches.map((s) => `| ${s.hex} | ${pct(s.share, 1)} |`),
    "",
    `Method: ${x.palette.method}.`,
    "",
    "## Structure",
    "",
    `- RMS contrast: ${x.structure.lumaStdDev.toFixed(3)} (measured)`,
    `- Edge density: ${pct(x.structure.edgeDensity, 1)} (measured)`,
    `- Detail centre: ${pct(x.structure.detailCentroid.x)} across, ${pct(x.structure.detailCentroid.y)} down (measured)`,
    `- Quiet area: ${pct(x.structure.quietShare)} (estimated)`,
    "",
    "_Generated by FrameProof._",
  ].join("\n");
}

function styleFromAsset(a: Asset): StyleSystem {
  const now = Date.now();
  return {
    id: newId("sty"),
    name: `Style from ${a.name.replace(/\.[a-z0-9]+$/i, "")}`,
    // Names are neutral on purpose: pixel share says nothing about a colour's role. Rename them yourself.
    // Swatches under 1% are usually anti-aliasing between shapes, so they're left out.
    palette: a.analysis.palette.swatches
      .filter((s) => s.share >= 0.01)
      .map((s, i) => ({ name: `Colour ${i + 1}`, hex: s.hex, share: s.share, origin: "measured" as const })),
    typography: { display: "", body: "", mono: "", notes: "Set these yourself — typefaces can't be identified reliably from pixels." },
    layoutPrinciples: [],
    spacing: [],
    radius: [],
    motion: [],
    referenceIds: [],
    sourceAssetId: a.id,
    notes: "",
    createdAt: now,
    updatedAt: now,
  };
}

function Observations({ items }: { items: Observation[] }) {
  return (
    <section aria-labelledby="obs-h" style={{ display: "grid", gap: "1rem" }}>
      <div>
        <h2 id="obs-h" className="t-heading">
          What the pixels show
        </h2>
        <p className="t-small t-measure" style={{ marginTop: "0.25rem" }}>
          Read from the measurements below, with the threshold each one uses. They describe the image; they don&apos;t judge it.
        </p>
      </div>
      <ul style={{ listStyle: "none", padding: 0, margin: 0, display: "grid", gap: "1.25rem" }} data-testid="observations">
        {items.map((o) => (
          <li key={o.id} data-testid="observation" style={{ borderTop: "1px solid var(--color-rule)", paddingTop: "0.9rem" }}>
            <h3 className="t-subhead">{o.title}</h3>
            <p className="proofnote-meta">
              <EvidenceLabel type={o.evidenceType} />
            </p>
            <p className="t-measure" style={{ fontSize: "var(--text-sm)" }}>
              {o.detail}
            </p>
            <details className="disclose" style={{ marginTop: "0.5rem" }}>
              <summary>Evidence</summary>
              <dl>
                {o.evidence.map((e) => (
                  <div key={e.label}>
                    <dt>{e.label}</dt>
                    <dd className="t-value">{e.value}</dd>
                  </div>
                ))}
                {o.limit ? (
                  <div>
                    <dt>What this can&apos;t tell you</dt>
                    <dd>{o.limit}</dd>
                  </div>
                ) : null}
              </dl>
            </details>
          </li>
        ))}
      </ul>
    </section>
  );
}

function Result({ asset }: { asset: Asset }) {
  const router = useRouter();
  const url = useObjectUrl(asset.blob);
  const [error, setError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const observations = observeImage(asset.analysis);
  return (
    <div className="spread">
      <div style={{ minWidth: 0, display: "grid", gap: "2rem" }}>
        {url ? <ImageViewer src={url} alt={asset.name} label={asset.name} /> : null}
        <Observations items={observations} />
        <MeasurementTable reference={asset.analysis} />
      </div>
      <aside className="margin" aria-label="Colour" style={{ display: "grid", gap: "1.75rem", alignContent: "start" }}>
        <section>
          <h2 className="t-heading" style={{ marginBottom: "0.75rem" }}>
            Palette
          </h2>
          <PaletteList analysis={asset.analysis} />
        </section>
        <ContrastPicker analysis={asset.analysis} />
        <section style={{ display: "grid", gap: "0.5rem" }}>
          <h2 className="t-subhead">Keep or export</h2>
          <button
            type="button"
            className="btn"
            disabled={saving}
            onClick={async () => {
              setSaving(true);
              setError(null);
              try {
                const s = await saveStyle(styleFromAsset(asset));
                toast("Style saved");
                router.push(`/styles?id=${s.id}`);
              } catch (e) {
                setError(e instanceof Error ? e.message : "The style couldn’t be saved.");
              } finally {
                setSaving(false);
              }
            }}
          >
            Save palette as a style
          </button>
          {error ? (
            <p role="alert" className="error-text">
              {error}
            </p>
          ) : null}
          <div style={{ display: "flex", gap: "0.5rem", flexWrap: "wrap" }}>
            <button
              type="button"
              className="btn btn-sm"
              onClick={() => download(`${fileSlug(asset.name)}-analysis.md`, analysisMarkdown(asset), "text/markdown;charset=utf-8")}
            >
              Export analysis (.md)
            </button>
            <button
              type="button"
              className="btn btn-sm"
              onClick={() =>
                download(
                  `${fileSlug(asset.name)}-analysis.json`,
                  JSON.stringify({ schema: "frameproof.analysis/v1", name: asset.name, analysis: asset.analysis, observations }, null, 2),
                  "application/json",
                )
              }
            >
              Export JSON
            </button>
          </div>
        </section>
      </aside>
    </div>
  );
}

export function Analyzer() {
  const params = useSearchParams();
  const router = useRouter();
  const assetId = params.get("asset");
  const current = useStore(() => (assetId ? getAsset(assetId) : Promise.resolve(undefined)), ["assets"], [assetId]);
  const recent = useStore(
    async () =>
      (await listAssets())
        .filter((a) => a.projectId === null)
        .sort((a, b) => b.createdAt - a.createdAt)
        .slice(0, 8),
    ["assets"],
  );
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const onFile = async (f: File) => {
    setBusy(true);
    setError(null);
    try {
      const a = await saveAsset(f, f.name, null);
      router.push(`/analyze?asset=${a.id}`);
      toast("Analysis saved");
    } catch (e) {
      setError(e instanceof Error ? e.message : "The image couldn't be analysed.");
    } finally {
      setBusy(false);
    }
  };

  const asset = current.status === "ready" ? current.data : undefined;

  return (
    <div className="page">
      <div className="folio">
        <h1 className="t-display">Analyzer</h1>
        <p className="t-meta">One image: palette, contrast and structure, measured in your browser.</p>
      </div>

      {current.status === "error" || recent.status === "error" ? (
        <p role="alert" className="error-text">
          {current.status === "error" ? current.message : recent.status === "error" ? recent.message : ""}
        </p>
      ) : null}
      {assetId && current.status === "ready" && !asset ? (
        <p className="notice" role="status" style={{ marginBottom: "1.5rem" }}>
          That analysis isn&apos;t in this browser any more. Drop an image to start a new one.
        </p>
      ) : null}

      {asset ? (
        <>
          <Result key={asset.id} asset={asset} />
          <hr className="rule" style={{ margin: "3rem 0 2rem" }} />
        </>
      ) : null}

      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(min(100%, 18rem), 1fr))", gap: "2rem", alignItems: "start" }}>
        <section aria-label="Analyze an image">
          <h2 className="t-heading" style={{ marginBottom: "0.75rem" }}>
            {asset ? "Analyze another image" : "Analyze an image"}
          </h2>
          <Dropzone label="Choose an image to analyze" busy={busy} error={error} onFile={onFile} testId="upload-analyze" />
          <p className="t-small" style={{ marginTop: "0.5rem" }}>
            The image stays in this browser. Nothing is uploaded.
          </p>
        </section>
        <section aria-labelledby="recent-h">
          <h2 id="recent-h" className="t-heading" style={{ marginBottom: "0.75rem" }}>
            Recent analyses
          </h2>
          {recent.status === "ready" && recent.data.length ? (
            <ul className="ledger">
              {recent.data.map((a) => (
                <li key={a.id}>
                  <Link
                    href={`/analyze?asset=${a.id}`}
                    className="ledger-row"
                    style={{ gridTemplateColumns: "3rem minmax(0,1fr) auto", padding: "0.6rem 0" }}
                    aria-current={a.id === assetId ? "true" : undefined}
                  >
                    <Thumb blob={a.thumb} alt="" style={{ maxWidth: "3rem", maxHeight: "3rem", objectFit: "contain", border: "1px solid var(--color-rule)" }} />
                    <span style={{ overflowWrap: "anywhere" }}>{a.name}</span>
                    <span className="t-value t-meta">
                      {a.width}×{a.height}
                    </span>
                  </Link>
                </li>
              ))}
            </ul>
          ) : (
            <p className="t-meta">Images you analyze are listed here.</p>
          )}
        </section>
      </div>
    </div>
  );
}
