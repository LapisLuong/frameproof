import type { ImageAnalysis } from "../analysis/analyze";
import type { Project, Review, StyleSystem } from "../store/models";
import { CATEGORY_LABEL, EVIDENCE_LABEL } from "./types";

const pct = (v: number, d = 0) => `${(v * 100).toFixed(d)}%`;
const date = (t: number) => new Date(t).toISOString().slice(0, 16).replace("T", " ");

/** Escape characters that would break Markdown tables or inject markup when rendered elsewhere. */
export function mdEscape(s: string): string {
  return s.replace(/[\\`*_{}[\]<>|]/g, (c) => `\\${c}`).replace(/\r?\n/g, " ");
}

function imageBlock(title: string, a: ImageAnalysis): string {
  const sw = a.palette.swatches.map((s) => `${s.hex} ${pct(s.share)}`).join(", ");
  return [
    `### ${title}`,
    "",
    `| Measure | Value |`,
    `| --- | --- |`,
    `| Size | ${a.width}×${a.height} px (${a.aspect.label}) |`,
    `| Palette | ${sw} |`,
    `| RMS contrast | ${a.structure.lumaStdDev.toFixed(3)} |`,
    `| Edge density | ${pct(a.structure.edgeDensity, 1)} |`,
    `| Quiet area (estimated) | ${pct(a.structure.quietShare)} |`,
    `| Detail centre | ${pct(a.structure.detailCentroid.x)} across, ${pct(a.structure.detailCentroid.y)} down |`,
    "",
  ].join("\n");
}

export function reviewToMarkdown(project: Project, review: Review): string {
  const open = review.issues.filter((i) => !i.resolved);
  const done = review.issues.filter((i) => i.resolved);
  const m = review.measurements;
  const lines: string[] = [
    `# Revision brief — ${mdEscape(project.name)}`,
    "",
    `Review ${review.version} · ${date(review.createdAt)} · ${open.length} open, ${done.length} resolved`,
    "",
  ];
  if (project.brief) lines.push(`> ${mdEscape(project.brief)}`, "");
  lines.push(
    "Evidence labels: **Measured** = computed from pixels with a stated method; **Estimated** = computed, but the interpretation rests on an assumption; **AI-observed** = a vision model's judgement.",
    "",
  );
  if (review.ai.state === "ok") lines.push(`AI review: ${mdEscape(review.ai.provider)} / ${mdEscape(review.ai.model)}. ${mdEscape(review.ai.summary)}`, "");
  else if (review.ai.state === "failed") lines.push(`AI review failed: ${mdEscape(review.ai.message)}. Only local measurements are included.`, "");
  else lines.push("AI review was not run. Findings below come from local measurements only.", "");

  const section = (title: string, list: typeof open) => {
    lines.push(`## ${title}`, "");
    if (!list.length) lines.push("None.", "");
    list.forEach((i, n) => {
      lines.push(
        `### ${n + 1}. ${mdEscape(i.title)}`,
        "",
        `${CATEGORY_LABEL[i.category]} · priority ${i.priority} · confidence ${i.confidence} · ${EVIDENCE_LABEL[i.evidenceType]}`,
        "",
        `- **What's wrong:** ${mdEscape(i.observation)}`,
        `- **Why it matters:** ${mdEscape(i.rationale)}`,
        `- **What to change:** ${mdEscape(i.recommendation)}`,
      );
      if (i.preserve) lines.push(`- **What to keep:** ${mdEscape(i.preserve)}`);
      if (i.evidence.length) lines.push(`- **Evidence:** ${i.evidence.map((e) => `${mdEscape(e.label)} \`${e.value.replace(/`/g, "'")}\``).join("; ")}`);
      lines.push("");
    });
  };
  section("Open", open);
  section("Resolved", done);

  if (review.notes) lines.push("## Notes", "", mdEscape(review.notes), "");
  lines.push(
    "## Measurements",
    "",
    imageBlock("Reference", m.reference),
    imageBlock("Current", m.current),
    "### Comparison",
    "",
    `${m.comparison.canvas.note}`,
    "",
    `| Measure | Value | What it does not tell you |`,
    `| --- | --- | --- |`,
    `| SSIM (luma) | ${m.comparison.ssim.toFixed(3)} | Sensitive to small shifts; not a quality score |`,
    `| dHash distance | ${m.comparison.dHashDistance} / 64 | Ignores colour |`,
    `| Colour histogram overlap | ${pct(m.comparison.histogramIntersection)} | Ignores where colours sit |`,
    `| Changed area (luma Δ > 0.1) | ${pct(m.comparison.changedShare)} | A change can be an improvement |`,
    "",
    "_Generated by FrameProof. No composite score is given on purpose._",
  );
  return lines.join("\n");
}

export function reviewToJson(project: Project, review: Review): string {
  return JSON.stringify(
    {
      schema: "frameproof.review/v1",
      exportedAt: new Date().toISOString(),
      project: { id: project.id, name: project.name, brief: project.brief },
      review: {
        id: review.id,
        version: review.version,
        createdAt: new Date(review.createdAt).toISOString(),
        ai: review.ai,
        notes: review.notes,
        issues: review.issues,
        measurements: review.measurements,
      },
    },
    null,
    2,
  );
}

const slug = (s: string) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/đ/g, "d").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "token";

export function styleToCss(style: StyleSystem): string {
  const lines = [`/* ${style.name.replace(/\*\//g, "")} — exported from FrameProof */`, ":root {"];
  for (const c of style.palette) lines.push(`  --color-${slug(c.name)}: ${c.hex};${c.origin === "measured" ? " /* measured from image */" : ""}`);
  lines.push(`  --font-display: ${JSON.stringify(style.typography.display || "serif")};`);
  lines.push(`  --font-body: ${JSON.stringify(style.typography.body || "sans-serif")};`);
  lines.push(`  --font-mono: ${JSON.stringify(style.typography.mono || "monospace")};`);
  for (const t of style.spacing) lines.push(`  --space-${slug(t.name)}: ${t.value};`);
  for (const t of style.radius) lines.push(`  --radius-${slug(t.name)}: ${t.value};`);
  lines.push("}");
  return lines.join("\n");
}

export function styleToJson(style: StyleSystem): string {
  return JSON.stringify(
    {
      schema: "frameproof.style/v1",
      name: style.name,
      color: Object.fromEntries(style.palette.map((c) => [slug(c.name), { value: c.hex, origin: c.origin, ...(c.share != null ? { share: c.share } : {}) }])),
      typography: style.typography,
      spacing: Object.fromEntries(style.spacing.map((t) => [slug(t.name), t.value])),
      radius: Object.fromEntries(style.radius.map((t) => [slug(t.name), t.value])),
      layoutPrinciples: style.layoutPrinciples,
      motion: style.motion,
      notes: style.notes,
      provenance:
        "Colours marked 'measured' were computed from an image's pixels. Type, spacing and radius are set by the user — they can't be recovered from a screenshot.",
    },
    null,
    2,
  );
}

export function download(filename: string, content: string, type: string): void {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

